def canonical_lab_field(label: str):
    key = label.lower().replace(":", "")
    key = re.sub(r"[^a-z0-9-]+", " ", key)
    key = clean_text(key)
    return LAB_FIELD_ALIASES.get(key, "")


def parse_lab_field_line(line: str):
    match = re.match(r"^-?\s*\*\*([^*]+?):\*\*\s*(.*)$", line)
    if match:
        return canonical_lab_field(match.group(1)), clean_text(match.group(2))

    match = re.match(r"^\*\*([^*]+)\*\*\s*$", line)
    if match:
        return canonical_lab_field(match.group(1)), ""

    return "", ""


def parse_lab_summary(path: Path):
    text = path.read_text(encoding="utf-8")
    sections = {}
    current = None
    current_heading = None

    for raw in text.splitlines():
        line = raw.rstrip()
        if re.match(r"^###\s+(Lab\s+\d+|P\d+(?:-\d+|/\d+)*|Project\s+\d+.*)", line):
            if current is not None and current_heading is not None:
                sections[current_heading] = current
            current_heading = line.split("###", 1)[1].strip()
            current = []
        elif current is not None:
            current.append(line)

    if current is not None and current_heading is not None:
        sections[current_heading] = current

    lab_rows = []
    for heading, block in sections.items():
        # Match headings like: Lab 1: R Intro, P1-1: Project 1 Logistics, etc.
        title = heading.split(":", 1)[0].strip()

        fields = {"lecture_anchor": "", "purpose": "", "objectives": [], "deliverables": []}
        current_field = ""
        purpose_lines = []
        for line in block:
            stripped = line.strip()
            if not stripped:
                continue

            field, value = parse_lab_field_line(stripped)
            if field:
                current_field = field
                if field in {"objectives", "deliverables"}:
                    if value:
                        fields[field].append(value)
                elif field in fields:
                    fields[field] = value
                continue

            if stripped.startswith("- "):
                value = clean_text(stripped[2:])
                if current_field in {"objectives", "deliverables"}:
                    fields[current_field].append(value)
                elif current_field == "purpose":
                    purpose_lines.append(value)

        if not fields["purpose"] and purpose_lines:
            fields["purpose"] = " ".join(purpose_lines)

        row = {
            "heading": heading,
            "title": title,
            "purpose": fields["purpose"],
            "lecture_anchor": fields["lecture_anchor"],
            "week": None,
            "objectives": " | ".join(fields["objectives"]),
            "objective_list": fields["objectives"],
            "deliverables": " | ".join(fields["deliverables"]),
            "flags": [],
        }

        for split_title in split_combined_lab_titles(title):
            lab_rows.append({**row, "title": split_title})

    for index, row in enumerate(lab_rows, start=1):
        row["week"] = index

    return lab_rows


def build_week_table(lecture_rows, lab_rows):
    # group lectures by week
    week_to_lectures = defaultdict(list)
    for row in lecture_rows:
        week_to_lectures[row["week"]].append(row)

    # build schedule rows for all relevant weeks, including project sessions
    all_weeks = set(week_to_lectures.keys())
    for lab in lab_rows:
        if lab["week"] is not None:
            all_weeks.add(lab["week"])

    rows = []
    for week in sorted(all_weeks):
        lectures = week_to_lectures.get(week, [])
        lecture_labels = ", ".join([r["label"] for r in lectures])
        lecture_topics = "; ".join(
            [f"{r['label']}: {r['topic']}" if r["topic"] else r["label"] for r in lectures]
        )
        flags = []
        for row in lectures:
            for flag in row.get("flags", []):
                flags.append(f"{row['label']}: {flag}")
        labs = []
        lab_deliverables = []
        for lab in lab_rows:
            if lab["week"] == week:
                anchor = lab["lecture_anchor"]
                labs.append(f"{lab['title']} ({anchor})" if anchor else lab["title"])
                if lab["deliverables"]:
                    lab_deliverables.append(f"{lab['title']}: {lab['deliverables']}")
                for flag in lab.get("flags", []):
                    flags.append(f"{lab['title']}: {flag}")

        rows.append(
            {
                "Week": week,
                "Lecture #": lecture_labels,
                "Lecture Topics": lecture_topics,
                "Labs": " | ".join(labs),
                "Lab Deliverables": " | ".join(lab_deliverables),
                "Instructor Flags": " | ".join(dict.fromkeys(flags)),
            }
        )

    return pd.DataFrame(rows)


def write_schedule_table(df: pd.DataFrame, xlsx_path: Path, sheet_name: str):
    if xlsx_path.exists():
        wb = load_workbook(xlsx_path)
        if sheet_name in wb.sheetnames:
            ws = wb[sheet_name]
            wb.remove(ws)
        ws = wb.create_sheet(title=sheet_name)
    else:
        wb = Workbook()
        ws = wb.active
        ws.title = sheet_name

    # write headers
    headers = list(df.columns)
    ws.append(headers)

    # write values
    for _, row in df.iterrows():
        ws.append([row[col] for col in headers])

    # style header row
    header_fill = PatternFill("solid", fgColor="D9EAF7")
    header_font = Font(bold=True)
    for cell in ws[1]:
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center", vertical="center")

    # auto-size columns
    for col in ws.columns:
        max_len = 0
        column = col[0].column_letter
        for cell in col:
            try:
                if cell.value is not None:
                    max_len = max(max_len, len(str(cell.value)))
            except Exception:
                pass
        ws.column_dimensions[column].width = min(max_len + 3, 80)

    wb.save(xlsx_path)


