def event_card(kind: str, title: str, details: str = "", meta: str = "", time_range: str = "") -> str:
    lines = [f'<article class="calendar-event calendar-event--{kind}">']
    lines.append(f'<div class="calendar-event__kind">{escape(kind.replace("-", " ").title())}</div>')
    lines.append(f'<h3>{escape(title)}</h3>')
    if time_range:
        lines.append(f'<p class="calendar-event__time">{escape(time_range)}</p>')
    if details:
        lines.append(f"<p>{escape(details)}</p>")
    if meta:
        lines.append(f'<p class="calendar-event__meta">{escape(meta)}</p>')
    lines.append("</article>")
    return "\n".join(lines)


def ics_escape(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace(";", "\\;")
        .replace(",", "\\,")
        .replace("\n", "\\n")
    )


def fold_ics_line(line: str) -> list[str]:
    if len(line) <= 75:
        return [line]
    folded = [line[:75]]
    rest = line[75:]
    while rest:
        folded.append(" " + rest[:74])
        rest = rest[74:]
    return folded


def write_ics_calendar(events, ics_path: Path, config: CourseSiteConfig):
    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        f"PRODID:-//{config.course_code}//Course Calendar//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        f"X-WR-CALNAME:{config.course_title} Course Calendar",
        f"X-WR-TIMEZONE:{config.local_timezone}",
    ]

    for event_date in sorted(events):
        for index, item in enumerate(events[event_date], start=1):
            title = item["title"]
            details = item.get("details", "")
            meta = item.get("meta", "")
            description = details if not meta else f"{details}\n{meta}" if details else meta
            uid_text = re.sub(r"[^A-Za-z0-9]+", "-", f"{event_date}-{index}-{title}").strip("-")
            event_lines = [
                "BEGIN:VEVENT",
                f"UID:{uid_text}@{config.course_code.lower()}-course-calendar",
                "DTSTAMP:20260101T000000Z",
            ]
            start_time = item.get("start_time", "")
            end_time = item.get("end_time", "")
            if start_time and end_time:
                start_dt = time_for_ics(event_date, start_time)
                end_dt = time_for_ics(event_date, end_time)
                event_lines.extend(
                    [
                        f"DTSTART;TZID={config.local_timezone}:{start_dt:%Y%m%dT%H%M%S}",
                        f"DTEND;TZID={config.local_timezone}:{end_dt:%Y%m%dT%H%M%S}",
                    ]
                )
            elif end_time:
                due_dt = time_for_ics(event_date, end_time)
                event_lines.append(f"DTSTART;TZID={config.local_timezone}:{due_dt:%Y%m%dT%H%M%S}")
            elif start_time:
                start_dt = time_for_ics(event_date, start_time)
                event_lines.append(f"DTSTART;TZID={config.local_timezone}:{start_dt:%Y%m%dT%H%M%S}")
            else:
                next_day = event_date + timedelta(days=1)
                event_lines.extend(
                    [
                        f"DTSTART;VALUE=DATE:{event_date:%Y%m%d}",
                        f"DTEND;VALUE=DATE:{next_day:%Y%m%d}",
                    ]
                )
            event_lines.append(f"SUMMARY:{ics_escape(title)}")
            if description:
                event_lines.append(f"DESCRIPTION:{ics_escape(description)}")
            event_lines.append("END:VEVENT")
            for line in event_lines:
                lines.extend(fold_ics_line(line))

    lines.append("END:VCALENDAR")
    ics_path.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")


def build_calendar_events(
    lecture_rows,
    lab_rows,
    important_dates,
    meeting_patterns,
    include_instructor_flags: bool = True,
    default_year: int = DEFAULT_TERM_YEAR,
):
    events = defaultdict(list)
    important_by_day = important_dates_by_day(important_dates)
    term_start, term_end = term_bounds(important_dates, default_year)
    suspended = class_suspended_dates(important_dates)
    lab_weekday = meeting_patterns["lab"][0]
    lab_deliverable_weekday = meeting_patterns["lab_deliverable"][0]

    for row in lecture_rows:
        meeting_date = row.get("date")
        if meeting_date is None:
            continue
        label = row["label"]
        kind = row.get("kind", "quiz" if label.startswith("Quiz") else "lecture")
        details = row["topic"] or "Quiz in the scheduled course window."
        meta = " | ".join(row.get("flags", [])) if include_instructor_flags else ""
        start_time, end_time = event_time_range(meeting_patterns, "lecture")
        events[meeting_date].append(
            {
                "kind": kind,
                "title": label,
                "details": details,
                "meta": meta,
                "start_time": start_time,
                "end_time": end_time,
            }
        )

    for lab in lab_rows:
        if lab["week"] is None:
            continue
        lab_date = lab.get("date") or scheduled_weekday_date(term_start, lab["week"], lab_weekday, suspended)
        lab["date"] = lab_date
        existing_flags = list(lab.get("flags", []))
        lab["flags"] = list(dict.fromkeys(existing_flags + nearby_important_dates(lab_date, important_dates)))
        kind = "lab"
        start_time, end_time = event_time_range(meeting_patterns, "lab")
        meta_parts = []
        if lab["lecture_anchor"]:
            meta_parts.append(f"Anchor: {lab['lecture_anchor']}")
        if lab["deliverables"]:
            meta_parts.append(f"Deliverables: {lab['deliverables']}")
        if include_instructor_flags:
            meta_parts.extend(lab.get("flags", []))
        events[lab_date].append(
            {
                "kind": kind,
                "title": lab["title"],
                "details": lab["purpose"],
                "meta": " | ".join(meta_parts),
                "start_time": start_time,
                "end_time": end_time,
            }
        )

        if lab["deliverables"]:
            deliverable_date = scheduled_weekday_date(
                term_start,
                lab["week"],
                lab_deliverable_weekday,
                suspended,
            )
            if term_start <= deliverable_date <= term_end:
                start_time, end_time = event_time_range(meeting_patterns, "lab_deliverable")
                events[deliverable_date].append(
                    {
                        "kind": "lab-deliverable",
                        "title": f"{lab['title']} Deliverables Due",
                        "details": lab["deliverables"],
                        "start_time": start_time,
                        "end_time": end_time,
                    }
                )

    max_week = max([row["week"] for row in lecture_rows] + [row["week"] for row in lab_rows if row["week"]])
    for week in range(1, max_week + 1):
        for discussion in meeting_patterns["discussion_patterns"]:
            for weekday in discussion["weekdays"]:
                discussion_date = scheduled_weekday_date(term_start, week, weekday, suspended, clamp_to_term_start=False)
                if term_start <= discussion_date <= term_end:
                    events[discussion_date].append(
                        {
                            "kind": "discussion",
                            "title": discussion["title"],
                            "details": "",
                            "start_time": discussion["start_time"],
                            "end_time": discussion["end_time"],
                        }
                    )
        for office_hour in meeting_patterns["office_hour_patterns"]:
            for weekday in office_hour["weekdays"]:
                office_hours_date = scheduled_weekday_date(
                    term_start,
                    week,
                    weekday,
                    suspended,
                    clamp_to_term_start=False,
                    shift_suspended=False,
                )
                if term_start <= office_hours_date <= term_end and office_hours_date not in suspended:
                    events[office_hours_date].append(
                        {
                            "kind": "office-hours",
                            "title": office_hour["title"],
                            "details": "",
                            "start_time": office_hour["start_time"],
                            "end_time": office_hour["end_time"],
                        }
                    )
        for weekday in meeting_patterns["homework"]:
            homework_date = scheduled_weekday_date(term_start, week, weekday, suspended, clamp_to_term_start=False)
            if term_start <= homework_date <= term_end:
                start_time, end_time = event_time_range(meeting_patterns, "homework")
                events[homework_date].append(
                    {
                        "kind": "homework",
                        "title": f"Homework Week {week}",
                        "details": "Weekly homework component.",
                        "start_time": start_time,
                        "end_time": end_time,
                    }
                )

    for day, descriptions in important_by_day.items():
        for description in descriptions:
            events[day].insert(
                0,
                {
                    "kind": "important-date",
                    "title": "Academic Calendar",
                    "details": description,
                },
            )

    return events


def month_grid_dates(year: int, month: int):
    first = date(year, month, 1)
    days_since_sunday = (first.weekday() + 1) % 7
    start = first - timedelta(days=days_since_sunday)
    return [start + timedelta(days=i) for i in range(42)]


def months_to_render(important_dates, default_year: int = DEFAULT_TERM_YEAR):
    term_start, term_end = term_bounds(important_dates, default_year)
    latest = term_end
    for row in important_dates:
        latest = max(latest, row["end"])

    months = []
    current = date(term_start.year, term_start.month, 1)
    final = date(latest.year, latest.month, 1)
    while current <= final:
        months.append(current)
        if current.month == 12:
            current = date(current.year + 1, 1, 1)
        else:
            current = date(current.year, current.month + 1, 1)
    return months


