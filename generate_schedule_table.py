def parse_quiz_schedule(path: Path):
    if not path.exists():
        return []

    rows = extract_table_after_heading(
        path.read_text(encoding="utf-8").splitlines(),
        "Quiz Schedule",
    )
    quiz_rows = []
    for row in rows:
        quiz = clean_text(row.get("quiz", ""))
        after_lecture = clean_text(row.get("after lecture", ""))
        if not quiz or not after_lecture:
            continue
        quiz_match = re.search(r"(\d+)", quiz)
        lecture_match = re.search(r"(\d+)", after_lecture)
        if not quiz_match or not lecture_match:
            continue
        status = clean_text(row.get("status", ""))
        notes = clean_text(row.get("notes", ""))
        quiz_rows.append(
            {
                "label": f"Quiz {int(quiz_match.group(1))}",
                "quiz_num": int(quiz_match.group(1)),
                "after_lecture": int(lecture_match.group(1)),
                "status": status,
                "notes": notes,
            }
        )
    return sorted(quiz_rows, key=lambda row: (row["after_lecture"], row["quiz_num"]))


