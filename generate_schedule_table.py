def clean_text(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def normalize_dash(text: str) -> str:
    return text.replace("–", "-").replace("—", "-")


def parse_month_day(month_day: str, default_year: int) -> date:
    m = re.match(r"^([A-Za-z]+)\s+(\d{1,2})$", month_day.strip())
    if not m:
        raise ValueError(f"Could not parse date: {month_day}")

    month_name, day = m.groups()
    month = list(calendar.month_name).index(month_name)
    year = default_year if month >= 8 else default_year + 1
    return date(year, month, int(day))


def split_markdown_table_row(line: str):
    if not line.startswith("|") or not line.endswith("|"):
        return None
    return [cell.strip() for cell in line.strip("|").split("|")]


def is_markdown_separator(cells):
    return all(re.fullmatch(r":?-{3,}:?", cell.strip()) for cell in cells)


def extract_table_after_heading(lines, heading: str):
    in_section = False
    table = []
    heading_pattern = re.compile(rf"^##\s+{re.escape(heading)}\s*$", re.IGNORECASE)

    for raw in lines:
        line = raw.rstrip()
        if heading_pattern.match(line):
            in_section = True
            continue
        if not in_section:
            continue
        if line.startswith("## ") and table:
            break

        cells = split_markdown_table_row(clean_text(line))
        if cells:
            table.append(cells)
        elif table:
            break

    if not table:
        return []

    headers = None
    rows = []
    for cells in table:
        if is_markdown_separator(cells):
            continue
        if headers is None:
            headers = [cell.lower() for cell in cells]
            continue
        rows.append(dict(zip(headers, cells)))
    return rows


def parse_weekday_list(text: str):
    weekdays = []
    parts = re.split(r",|/|;|\band\b", text, flags=re.IGNORECASE)
    for part in parts:
        key = clean_text(part).lower()
        if key in WEEKDAY_NUMBERS:
            weekdays.append(WEEKDAY_NUMBERS[key])
    return weekdays


def normalize_event_time(text: str):
    text = clean_text(text)
    if not text:
        return ""
    for fmt in ("%I:%M %p", "%I %p", "%H:%M"):
        try:
            return datetime.strptime(text.upper(), fmt).strftime("%I:%M %p").lstrip("0")
        except ValueError:
            continue
    return text


def read_row_time(row, fallback):
    start = normalize_event_time(row.get("start time", ""))
    end = normalize_event_time(row.get("end time", ""))
    if not start and not end:
        start, end = fallback
    return start, end


def event_time_range(meeting_patterns, event_key: str):
    return meeting_patterns.get("times", {}).get(event_key, DEFAULT_EVENT_TIMES[event_key])


def format_time_range(start: str, end: str):
    if start and end:
        return f"{start}-{end}"
    if end:
        return f"Due {end}"
    if start:
        return f"Starts {start}"
    return ""


def time_for_ics(event_date: date, time_text: str):
    parsed = datetime.strptime(normalize_event_time(time_text), "%I:%M %p")
    return datetime.combine(event_date, parsed.time())


def parse_meeting_patterns(lecture_path: Path, lab_path: Path):
    patterns = {
        "lecture": DEFAULT_LECTURE_WEEKDAYS,
        "lab": DEFAULT_LAB_WEEKDAYS,
        "lab_deliverable": DEFAULT_LAB_DELIVERABLE_WEEKDAYS,
        "discussion": DEFAULT_DISCUSSION_WEEKDAYS,
        "office_hours": DEFAULT_OFFICE_HOURS_WEEKDAYS,
        "homework": DEFAULT_HOMEWORK_WEEKDAYS,
        "times": DEFAULT_EVENT_TIMES.copy(),
        "office_hour_patterns": [],
    }

    lecture_rows = extract_table_after_heading(
        lecture_path.read_text(encoding="utf-8").splitlines(),
        "Course Meeting Pattern",
    )
    for row in lecture_rows:
        event_type = row.get("event type", "").lower()
        weekdays = parse_weekday_list(row.get("weekdays", ""))
        if not weekdays:
            continue
        if event_type == "lecture":
            patterns["lecture"] = weekdays
            patterns["times"]["lecture"] = read_row_time(row, DEFAULT_EVENT_TIMES["lecture"])
        elif event_type == "discussion":
            patterns["discussion"] = weekdays
            patterns["times"]["discussion"] = read_row_time(row, DEFAULT_EVENT_TIMES["discussion"])
        elif re.fullmatch(r"office hours?", event_type) or event_type.startswith("office hour "):
            patterns["office_hours"] = weekdays
            patterns["times"]["office_hours"] = read_row_time(row, DEFAULT_EVENT_TIMES["office_hours"])
            patterns["office_hour_patterns"].append(
                {
                    "title": row.get("event type", "Office Hours"),
                    "weekdays": weekdays,
                    "start_time": patterns["times"]["office_hours"][0],
                    "end_time": patterns["times"]["office_hours"][1],
                }
            )
        elif event_type == "homework":
            patterns["homework"] = weekdays
            patterns["times"]["homework"] = read_row_time(row, DEFAULT_EVENT_TIMES["homework"])

    lab_rows = extract_table_after_heading(
        lab_path.read_text(encoding="utf-8").splitlines(),
        "Lab Meeting Pattern",
    )
    for row in lab_rows:
        event_type = row.get("event type", "").lower()
        weekdays = parse_weekday_list(row.get("weekday", "") or row.get("weekdays", ""))
        if weekdays and event_type in {"lab", "lab / project", "lab/project", "project"}:
            patterns["lab"] = weekdays
            patterns["times"]["lab"] = read_row_time(row, DEFAULT_EVENT_TIMES["lab"])
        elif weekdays and event_type in {"lab deliverable", "lab deliverables", "deliverable", "deliverables"}:
            patterns["lab_deliverable"] = weekdays
            patterns["times"]["lab_deliverable"] = read_row_time(row, DEFAULT_EVENT_TIMES["lab_deliverable"])

    if not patterns["office_hour_patterns"]:
        start_time, end_time = event_time_range(patterns, "office_hours")
        patterns["office_hour_patterns"].append(
            {
                "title": "Office Hours",
                "weekdays": patterns["office_hours"],
                "start_time": start_time,
                "end_time": end_time,
            }
        )

    return patterns


def parse_important_dates_table(lines, current_year: int):
    rows = []
    headers = None
    for raw in lines:
        line = clean_text(raw)
        cells = split_markdown_table_row(line)
        if not cells:
            continue
        if is_markdown_separator(cells):
            continue
        if headers is None:
            headers = [cell.lower() for cell in cells]
            continue

        row = dict(zip(headers, cells))
        start_text = row.get("start date", "")
        end_text = row.get("end date", "")
        description = row.get("event", "")
        if not start_text or not description:
            continue

        start_date = parse_month_day(start_text, current_year)
        end_date = parse_month_day(end_text, current_year) if end_text else start_date
        rows.append({"start": start_date, "end": end_date, "description": description})

    return rows


def parse_important_dates(path: Path):
    if not path.exists():
        return []

    rows = []
    current_year = TERM_YEAR
    lines = path.read_text(encoding="utf-8").splitlines()
    for raw in lines:
        line = clean_text(raw)
        if not line:
            continue

        term_match = re.match(r"^(?:Semester\s*:?\s*)?[A-Za-z]+\s+(\d{4})$", line, re.IGNORECASE)
        if term_match:
            current_year = int(term_match.group(1))
            break

    table_rows = parse_important_dates_table(lines, current_year)
    if table_rows:
        return table_rows

    for raw in lines:
        line = clean_text(raw)
        if not line:
            continue

        term_match = re.match(r"^(?:Semester\s*:?\s*)?[A-Za-z]+\s+(\d{4})$", line, re.IGNORECASE)
        if term_match:
            current_year = int(term_match.group(1))
            continue

        line = normalize_dash(line)
        m = re.match(r"^([A-Za-z]+\s+\d{1,2})(?:\s*-\s*([A-Za-z]+\s+)?(\d{1,2}))?\s+(.+)$", line)
        if not m:
            continue

        start_text, end_month, end_day, description = m.groups()
        start_date = parse_month_day(start_text, current_year)
        if end_day:
            month_name = end_month.strip() if end_month else calendar.month_name[start_date.month]
            end_date = parse_month_day(f"{month_name} {end_day}", current_year)
        else:
            end_date = start_date

        rows.append({"start": start_date, "end": end_date, "description": description})

    return rows


def important_dates_by_day(important_dates):
    by_day = defaultdict(list)
    for row in important_dates:
        current = row["start"]
        while current <= row["end"]:
            by_day[current].append(row["description"])
            current += timedelta(days=1)
    return by_day


def find_important_date(important_dates, pattern: str):
    regex = re.compile(pattern, re.IGNORECASE)
    for row in important_dates:
        if regex.search(row["description"]):
            return row
    return None


def term_bounds(important_dates):
    start = find_important_date(important_dates, r"Classes Begin")
    end = find_important_date(important_dates, r"Last Day of Classes")
    if not start or not end:
        return date(TERM_YEAR, 9, 2), date(TERM_YEAR, 12, 10)
    return start["start"], end["start"]


def class_suspended_dates(important_dates):
    suspended = set()
    for row in important_dates:
        description = row["description"].lower()
        if "classes suspended" in description or "thanksgiving recess" in description or "study period" in description:
            current = row["start"]
            while current <= row["end"]:
                suspended.add(current)
                current += timedelta(days=1)
    return suspended


def substitute_meeting_dates(important_dates):
    substitutes = set()
    for row in important_dates:
        if "substitute a monday schedule" in row["description"].lower():
            substitutes.add(row["start"])
    return substitutes


def build_class_meeting_dates(important_dates, lecture_weekdays):
    start, end = term_bounds(important_dates)
    suspended = class_suspended_dates(important_dates)
    substitutes = substitute_meeting_dates(important_dates)
    lecture_weekdays = set(lecture_weekdays)
    meetings = []
    current = start
    while current <= end:
        if (
            current in substitutes
            or current == end
            or (current.weekday() in lecture_weekdays and current not in suspended)
        ):
            meetings.append(current)
        current += timedelta(days=1)
    return meetings


def week_start_for_week(start: date, week: int) -> date:
    first_monday = start - timedelta(days=start.weekday())
    return first_monday + timedelta(weeks=week - 1)


def scheduled_weekday_date(
    term_start: date,
    week: int,
    weekday: int,
    suspended_dates: set[date],
    clamp_to_term_start: bool = True,
    shift_suspended: bool = True,
) -> date:
    candidate = week_start_for_week(term_start, week) + timedelta(days=weekday)
    if clamp_to_term_start and candidate < term_start:
        candidate = term_start
    while shift_suspended and candidate in suspended_dates:
        candidate += timedelta(days=1)
    return candidate


def course_week_for_date(term_start: date, event_date: date) -> int:
    first_monday = term_start - timedelta(days=term_start.weekday())
    return ((event_date - first_monday).days // 7) + 1


def nearby_important_dates(event_date: date, important_dates, window_days: int = 2):
    flags = []
    for row in important_dates:
        if not FLAGGABLE_IMPORTANT_DATE.search(row["description"]):
            continue
        if row["start"] <= event_date <= row["end"]:
            flags.append(row["description"])
            continue
        before = row["start"] - timedelta(days=window_days)
        after = row["end"] + timedelta(days=window_days)
        if before <= event_date <= after:
            flags.append(f"Near {row['description']}")
    return flags


def week_for_lecture_num(num: int) -> int:
    # Fallback grouping for lecture blocks.
    return ((num - 1) // 3) + 1


